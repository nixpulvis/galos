-- Three labels Spansh's galaxy schema lists and this database had no word
-- for, found by reading every closed enum of that schema through the
-- reader rather than by losing a row to one.
--
-- A system whose government or economy has no label is a row Postgres
-- refuses, and its bodies go with it behind the foreign key -- which is
-- how the anarchy security reading cost 13% of a seven-day file. None of
-- these three appears in that file, so this is the same fault caught
-- before it is paid for.
ALTER TYPE government ADD VALUE IF NOT EXISTS 'PrivateOwnership';
ALTER TYPE economy ADD VALUE IF NOT EXISTS 'PrivateEnterprise';
ALTER TYPE economy ADD VALUE IF NOT EXISTS 'Repair';
